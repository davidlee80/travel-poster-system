-- 0007：素材内容指纹（TP-6-01，设计稿 9.6、十五章的 R-47）
--
-- ── 为什么需要这一列 ──
--
-- 9.6 的搜索入库流水线会把授权图源命中的图落成全平台共享资产。同一张原图
-- 会从多条路径重复到达：同城不同 POI 的检索词可能命中图源里的同一张图，
-- 同一 POI 在不同风格标签下会各搜一次，图源自己也会把一张图挂在多个词下。
--
-- 已有的 `assets_cache_key_uk` 拦不住这些：缓存键由**请求上下文**算出
-- （19.2），上下文不同键就不同，而图可以是同一张。结果是同一份字节在库里
-- 存成多行、在对象存储里存成多份，且检索时它们互相竞争排名 ——
-- 用户在不同天看到"不同"的图，其实是同一张。
--
-- ── 为什么只做字节级精确去重 ──
--
-- R-47：只比较原图字节的 SHA-256，不做感知哈希（pHash / dHash）的近似去重。
-- 两者的错误代价不对称：
--   - 精确去重漏判（同一景物的两个不同分辨率版本各存一份）代价是多存一张图，
--     几十 KB，且两行的评分各自独立，检索质量不受损；
--   - 近似去重错判（把两个不同景点的相似构图判为同一张）代价是张冠李戴 ——
--     库里从此少了一个景点的图，而那张图被挂在别的 POI 名下，
--     用户看到的是错误的地点，且没有任何报错。
-- 感知哈希需要阈值调参与人工复核样本，在 V1 的自动化入库前提下不具备条件。
--
-- ── 为什么是可空 + 部分唯一索引 ──
--
-- 只有 `source_type = 'LICENSED_SOURCE'` 的行必填（9.6）。平台自有素材
-- （人工灌库，`assets:ingest`）与 AI 生成物不参与指纹去重：
--   - 平台素材由人挑选入库，重复是入库时就该发现的问题，不需要数据库兜；
--   - AI 生成物本来就每次不同（`seed` 由缓存键派生），字节相同只可能是
--     同键并发，而那一层已经由 `assets_cache_key_uk` 与 13.8 的锁挡住了。
-- 用 NOT NULL + 空串占位会让"没有指纹"与"指纹是空串"无法区分，
-- 且空串会在唯一索引里互相冲突 —— 第二个非搜索素材就插不进去了。
--
-- ── 与 assets_cache_key_uk 不合并到一个 ON CONFLICT ──
--
-- 两个索引的语义不同：缓存键冲突意味着"同一个请求上下文已经有产物了，
-- 复用它"；指纹冲突意味着"这份字节已经在库里了，把标签并进去"（R-47 的
-- 合并分支）。写在同一个 ON CONFLICT 子句里无法区分是哪一个撞了，
-- 因此指纹去重由调用方先查后插（apps/generation-worker/src/assets/search-ingest.ts），
-- 这个索引是并发下的最后一道。

ALTER TABLE assets
    ADD COLUMN IF NOT EXISTS content_hash CHAR(64);

COMMENT ON COLUMN assets.content_hash IS
    '原图字节的 SHA-256 十六进制（R-47）。LICENSED_SOURCE 必填，其余来源为 NULL';

CREATE UNIQUE INDEX IF NOT EXISTS assets_content_hash_uk
    ON assets (content_hash)
    WHERE content_hash IS NOT NULL;
